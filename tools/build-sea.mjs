#!/usr/bin/env node
/**
 * Builds the Windows single executable (Node SEA): DECISIONS §19.
 *
 *   npm run build:sea:win [-- --cache <dir>] [--out <file.exe>]
 *
 * Expects `npm run build` (tsc → dist/) to have run. Steps:
 *   1. esbuild dist/cli.js → build/sea/pump-sim.cjs (one CJS file, node22).
 *   2. Builds the frameless window host (tools/window-go, DECISIONS §32) with Go for windows/amd64
 *      into build/sea/pump-sim-janela.exe, plus its sha256.
 *   3. build/sea/sea-config.json: the bundle as `main`, every file under ui/ as asset `ui/<path>`,
 *      the host and its sha256 as `janela/pump-sim-janela.exe(.sha256)`, useCodeCache/useSnapshot
 *      false (a blob with code cache only runs on the platform that built it).
 *   4. node --experimental-sea-config → build/sea/sea-prep.blob. The blob format follows the Node
 *      version, so this must run on exactly NODE_VERSION.
 *   5. Downloads node-v<NODE_VERSION>-win-x64.zip into the cache folder (default build/sea/node),
 *      checks its sha256 against nodejs.org's SHASUMS256.txt and stops on any mismatch.
 *   6. Extracts node.exe, writes it without its signature to the output and injects the blob with
 *      postject.
 *   7. Replaces the icon with tools/icon/pump-sim.ico and the version info with pump-sim's (resedit,
 *      pure JS).
 *   8. Sets the PE Subsystem from console (3) to Windows GUI (2), recomputing the PE checksum when
 *      one is set (tools/pe.mjs, DECISIONS §34): a double click then opens no console window. Then
 *      reads the PE back and checks icon, version, blob, fuse and subsystem.
 *
 * Why the rebrand runs after postject: in node.exe .rsrc is followed by .reloc. Rewriting .rsrc
 * there with a smaller icon set makes resedit move .reloc and leave .rsrc's raw size larger than its
 * virtual size, and postject (LIEF) then reports "Relocation corrupted". postject moves .rsrc to the
 * end of the file, so a rewrite after it touches no other section.
 *
 * The result is unsigned: node.exe's signature is removed before the blob goes in (it would no
 * longer match), so Windows SmartScreen warns on first run (README).
 */
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { inject } from 'postject';
import * as ResEdit from 'resedit';
import { SUBSISTEMA_GUI, calcularChecksum, definirSubsistema, lerChecksum, lerSubsistema } from './pe.mjs';

const NODE_VERSION = '22.20.0';
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';
const RAIZ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SAIDA = path.join(RAIZ, 'build', 'sea');
const ICONE = path.join(RAIZ, 'tools', 'icon', 'pump-sim.ico');
const DIR_JANELA = path.join(RAIZ, 'tools', 'window-go');
const LANG_EN_US = 1033;
const CODEPAGE_UTF16 = 1200;

function arg(nome, padrao) {
  const i = process.argv.indexOf(nome);
  return i >= 0 && process.argv[i + 1] ? path.resolve(process.argv[i + 1]) : padrao;
}

function falhar(msg) {
  process.stderr.write(`[build-sea] ${msg}\n`);
  process.exit(1);
}

function log(msg) {
  process.stdout.write(`[build-sea] ${msg}\n`);
}

function sha256(arq) {
  return crypto.createHash('sha256').update(fs.readFileSync(arq)).digest('hex');
}

function listar(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? listar(p, base) : [path.relative(base, p).split(path.sep).join('/')];
  });
}

/**
 * Removes the Authenticode signature of a PE32+ file (what `signtool remove /s` does): zeroes the
 * certificate-table entry of the optional header and drops the table from the end of the file.
 * Injecting the blob would otherwise leave a corrupt signature that points into the new data.
 */
function tirarAssinatura(arq) {
  const b = fs.readFileSync(arq);
  const pe = b.readUInt32LE(0x3c);
  if (b.toString('latin1', pe, pe + 4) !== 'PE\0\0') falhar(`${arq} is not a PE file`);
  const opcional = pe + 24;
  if (b.readUInt16LE(opcional) !== 0x20b) falhar(`${arq} is not PE32+`);
  const entrada = opcional + 112 + 4 * 8; // data directory 4: certificate table
  const inicio = b.readUInt32LE(entrada);
  const tamanho = b.readUInt32LE(entrada + 4);
  if (!tamanho) return b;
  if (inicio + tamanho !== b.length) falhar(`${arq}: certificate table is not at the end of the file`);
  b.writeUInt32LE(0, entrada);
  b.writeUInt32LE(0, entrada + 4);
  return b.subarray(0, inicio);
}

/**
 * Rebrands node.exe as pump-sim: swaps every icon group for tools/icon/pump-sim.ico (regenerated by
 * tools/gen-icons.mjs) and rewrites the version resource (Explorer's Details tab, Task Manager).
 * Runs on the unsigned PE after the blob is injected (.rsrc is then the last section); every other
 * resource, NODE_SEA_BLOB included, is written back unchanged.
 */
function marcar(pe, versao) {
  const exe = ResEdit.NtExecutable.from(pe, { ignoreCert: true });
  const res = ResEdit.NtExecutableResource.from(exe);
  const icones = ResEdit.Data.IconFile.from(fs.readFileSync(ICONE)).icons.map((i) => i.data);
  const grupos = ResEdit.Resource.IconGroupEntry.fromEntries(res.entries);
  if (!grupos.length) falhar('node.exe has no icon group to replace');
  for (const g of grupos) ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries, g.id, g.lang, icones);

  const [info] = ResEdit.Resource.VersionInfo.fromEntries(res.entries);
  if (!info) falhar('node.exe has no version resource');
  const partes = versao.split(/[.+-]/).slice(0, 3).map(Number);
  if (partes.length !== 3 || partes.some((n) => !Number.isInteger(n))) falhar(`package.json version ${versao} is not x.y.z`);
  const [maior, menor, patch] = partes;
  info.setFileVersion(maior, menor, patch, 0, LANG_EN_US);
  info.setProductVersion(maior, menor, patch, 0, LANG_EN_US);
  for (const l of info.getAllLanguagesForStringValues()) info.removeAllStringValues(l);
  info.setStringValues(
    { lang: LANG_EN_US, codepage: CODEPAGE_UTF16 },
    {
      CompanyName: 'Gabriel Martinusso',
      ProductName: 'pump-sim',
      FileDescription: 'pump-sim fuel concentrator simulator',
      FileVersion: versao,
      ProductVersion: versao,
      OriginalFilename: 'pump-sim-win-x64.exe',
      InternalName: 'pump-sim',
      LegalCopyright: 'MIT license. Built on Node.js (MIT license, Node.js contributors).',
    },
  );
  info.outputToResourceEntries(res.entries);
  res.outputResource(exe);
  return Buffer.from(exe.generate());
}

/** Reads the finished PE back: one icon group with the .ico's sizes, the version strings, the blob, the fuse and the GUI subsystem. */
function conferir(arq, tamanhoBlob, versao) {
  const b = fs.readFileSync(arq);
  const res = ResEdit.NtExecutableResource.from(ResEdit.NtExecutable.from(b, { ignoreCert: true }));
  const esperados = ResEdit.Data.IconFile.from(fs.readFileSync(ICONE)).icons.length;
  const grupos = ResEdit.Resource.IconGroupEntry.fromEntries(res.entries);
  if (grupos.length !== 1 || grupos[0].icons.length !== esperados) falhar(`icon group: expected 1 group with ${esperados} icons`);
  const icones = res.entries.filter((e) => e.type === 3).length;
  if (icones !== esperados) falhar(`expected ${esperados} RT_ICON entries, found ${icones}`);
  const [info] = ResEdit.Resource.VersionInfo.fromEntries(res.entries);
  const textos = info?.getStringValues({ lang: LANG_EN_US, codepage: CODEPAGE_UTF16 }) ?? {};
  if (textos.ProductName !== 'pump-sim' || textos.FileVersion !== versao) falhar('version info was not written');
  const sea = res.entries.find((e) => e.type === 10 && e.id === 'NODE_SEA_BLOB');
  if (!sea || sea.bin.byteLength !== tamanhoBlob) falhar('NODE_SEA_BLOB resource missing or resized');
  if (!b.includes(Buffer.from(`${FUSE}:1`))) falhar('SEA fuse not flipped');
  const sub = lerSubsistema(b);
  if (sub !== SUBSISTEMA_GUI) falhar(`PE subsystem is ${sub}, expected ${SUBSISTEMA_GUI} (Windows GUI)`);
  const soma = lerChecksum(b);
  if (soma !== 0 && soma !== calcularChecksum(b)) falhar('PE checksum does not match the file');
  return { subsistema: sub, checksum: soma };
}

/**
 * Builds tools/window-go for windows/amd64 (pure Go, CGO off, GUI subsystem so no console flashes)
 * and writes its sha256 next to it. Both become SEA assets; src/ui/janela.ts checks the sha before
 * every launch.
 */
function construirJanela() {
  const exe = path.join(SAIDA, 'pump-sim-janela.exe');
  try {
    execFileSync('go', ['build', '-trimpath', '-buildvcs=false', '-ldflags=-s -w -H windowsgui', '-o', exe, '.'], {
      cwd: DIR_JANELA,
      stdio: 'inherit',
      env: { ...process.env, GOOS: 'windows', GOARCH: 'amd64', CGO_ENABLED: '0' },
    });
  } catch (e) {
    falhar(`go build of tools/window-go failed (needs Go, version in tools/window-go/go.mod): ${e instanceof Error ? e.message : String(e)}`);
  }
  const sha = sha256(exe);
  const arqSha = `${exe}.sha256`;
  fs.writeFileSync(arqSha, sha);
  log(`window host ${path.relative(RAIZ, exe)} (${fs.statSync(exe).size} bytes) sha256 ${sha}`);
  return { exe, arqSha };
}

async function baixar(url, destino) {
  const r = await fetch(url);
  if (!r.ok) falhar(`GET ${url}: HTTP ${r.status}`);
  const tmp = `${destino}.part`;
  fs.writeFileSync(tmp, Buffer.from(await r.arrayBuffer()));
  fs.renameSync(tmp, destino);
}

async function main() {
  if (process.version !== `v${NODE_VERSION}`) falhar(`run on Node ${NODE_VERSION} (this is ${process.version}): the SEA blob must match the embedded node.exe`);
  const cache = arg('--cache', path.join(SAIDA, 'node'));
  const exe = arg('--out', path.join(SAIDA, 'pump-sim-win-x64.exe'));
  const entrada = path.join(RAIZ, 'dist', 'cli.js');
  if (!fs.existsSync(entrada)) falhar('dist/cli.js missing: run `npm run build` first');
  fs.mkdirSync(SAIDA, { recursive: true });
  fs.mkdirSync(cache, { recursive: true });
  fs.mkdirSync(path.dirname(exe), { recursive: true });

  // 1. Bundle.
  const bundle = path.join(SAIDA, 'pump-sim.cjs');
  await build({
    entryPoints: [entrada],
    outfile: bundle,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node22',
    // No import.meta in CJS: src/ui/assets.ts falls back to __dirname / process.execPath.
    define: { 'import.meta.url': 'undefined' },
    // ws loads these optional native add-ons inside try/catch.
    external: ['bufferutil', 'utf-8-validate'],
    logLevel: 'warning',
  });
  // dist/cli.js starts with a shebang; keep the SEA main plain JS.
  const fonte = fs.readFileSync(bundle, 'utf8');
  if (fonte.startsWith('#!')) fs.writeFileSync(bundle, fonte.replace(/^#![^\n]*\n/, ''));
  log(`bundle ${path.relative(RAIZ, bundle)} (${fs.statSync(bundle).size} bytes)`);

  // 2. Window host.
  const janela = construirJanela();

  // 3. SEA config.
  const dirUi = path.join(RAIZ, 'ui');
  const assets = Object.fromEntries(listar(dirUi).map((rel) => [`ui/${rel}`, path.join(dirUi, rel)]));
  // Keys match ASSET_JANELA / ASSET_JANELA_SHA in src/ui/janela.ts.
  assets['janela/pump-sim-janela.exe'] = janela.exe;
  assets['janela/pump-sim-janela.exe.sha256'] = janela.arqSha;
  const blob = path.join(SAIDA, 'sea-prep.blob');
  const config = path.join(SAIDA, 'sea-config.json');
  fs.writeFileSync(
    config,
    // main is relative (node runs in SAIDA): the blob stores it as the script's filename, which shows
    // up in every stack trace of the executable; an absolute path would leak the build machine's.
    JSON.stringify({ main: path.basename(bundle), output: blob, disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false, assets }, null, 2),
  );
  log(`sea-config: ${Object.keys(assets).length} assets (ui + window host)`);

  // 4. Blob.
  execFileSync(process.execPath, ['--experimental-sea-config', config], { stdio: 'inherit', cwd: SAIDA });

  // 5. Official node.exe, checked against SHASUMS256.txt.
  const nomeZip = `node-v${NODE_VERSION}-win-x64.zip`;
  const base = `https://nodejs.org/dist/v${NODE_VERSION}`;
  const shasums = await (await fetch(`${base}/SHASUMS256.txt`)).text();
  const linha = shasums.split('\n').find((l) => l.trim().endsWith(`  ${nomeZip}`));
  if (!linha) falhar(`${nomeZip} not listed in ${base}/SHASUMS256.txt`);
  const esperado = linha.trim().split(/\s+/)[0];
  const zip = path.join(cache, nomeZip);
  if (!fs.existsSync(zip)) {
    log(`downloading ${base}/${nomeZip}`);
    await baixar(`${base}/${nomeZip}`, zip);
  }
  const obtido = sha256(zip);
  if (obtido !== esperado) falhar(`sha256 mismatch for ${zip}: expected ${esperado}, got ${obtido}. Delete it and retry; do not ship.`);
  log(`sha256 ok ${obtido}`);
  const dirZip = path.join(cache, `node-v${NODE_VERSION}-win-x64`);
  const nodeExe = path.join(dirZip, 'node.exe');
  if (!fs.existsSync(nodeExe)) {
    // bsdtar (macOS, Windows 10+) and GNU tar with zip support both read .zip.
    execFileSync('tar', ['-xf', zip, '-C', cache, `node-v${NODE_VERSION}-win-x64/node.exe`], { stdio: 'inherit' });
  }

  // 6. Unsign, inject.
  fs.writeFileSync(exe, tirarAssinatura(nodeExe));
  const dadosBlob = fs.readFileSync(blob);
  await inject(exe, 'NODE_SEA_BLOB', dadosBlob, { sentinelFuse: FUSE, overwrite: true });

  // 7. Rebrand, then read the result back.
  const { version } = JSON.parse(fs.readFileSync(path.join(RAIZ, 'package.json'), 'utf8'));
  const marcado = marcar(fs.readFileSync(exe), version);
  // 8. GUI subsystem: no console on a double click; stdout/stderr go to the log file (src/ui/log.ts).
  const sub = definirSubsistema(marcado, SUBSISTEMA_GUI);
  fs.writeFileSync(exe, marcado);
  const lido = conferir(exe, dadosBlob.length, version);
  log(`icon ${path.relative(RAIZ, ICONE)}, version info pump-sim ${version}`);
  log(`PE subsystem ${sub.antes} -> ${lido.subsistema} (read back), checksum ${lido.checksum ? `0x${lido.checksum.toString(16)}` : 'not set'}`);
  log(`${exe} ${fs.statSync(exe).size} bytes sha256 ${sha256(exe)}`);
}

main().catch((e) => falhar(e instanceof Error ? e.stack ?? e.message : String(e)));
